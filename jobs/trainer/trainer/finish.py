"""After training: every report and chart, the leaderboard, model cards, and registration.

    python -m trainer.finish snapshots/NAME
    python -m trainer.finish snapshots/NAME --register

Everything comes from each model's saved report and served artifact, so this can be rerun without
training. Registering adds versions and sets aliases from the leaderboard. Its order is the only
thing that decides the champion.
"""

import argparse
import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

import numpy as np
from mlflow import MlflowClient
from wikiguard_core.evaluation import at_threshold, pr_auc
from wikiguard_core.inference import ServedModel
from wikiguard_core.models import MLP, MODEL_NAMES
from wikiguard_core.tracking import configure, register_version, set_aliases

from trainer import charts
from trainer.data import labels_of, load_dataset
from trainer.report import SCORING_THREADS
from trainer.robustness import robustness_report

RUNS_FOLDER = Path("data/runs")
IMAGES_FOLDER = Path("docs/images")
CARDS_FOLDER = Path("docs/model-cards")
GOLDEN_FILE = Path("snapshots/golden-set-v1/golden.json")
SCORES_FILE = "scores.npz"


def load_reports() -> dict[str, dict[str, Any]]:
    reports = {}
    for name in MODEL_NAMES:
        path = RUNS_FOLDER / name / "report.json"
        if path.exists():
            reports[name] = json.loads(path.read_text("utf-8"))
    return reports


def read_json(path: Path) -> Any:
    return json.loads(path.read_text("utf-8")) if path.exists() else None


def golden_report(model: ServedModel, golden: dict[str, Any], threshold: float) -> dict[str, Any]:
    rows = golden["rows"]
    labels = np.array([row["checked_label"] for row in rows], dtype=np.int64)
    logits = model.logits(rows)
    return {
        "rows": len(rows),
        "pr_auc": pr_auc(labels, logits),
        "at_threshold": at_threshold(labels, logits, threshold),
    }


def leaderboard_rows(reports: dict[str, dict[str, Any]], baselines: Any) -> list[dict[str, Any]]:
    rows = [
        {
            "name": name,
            "pr_auc": report["pr_auc"],
            "pr_auc_interval": report["pr_auc_interval"],
        }
        for name, report in reports.items()
    ]
    if baselines:
        rule = baselines["test"]["rule"]
        rows.append(
            {
                "name": "rule",
                "label": "Rule baseline",
                "pr_auc": rule["pr_auc"],
                "pr_auc_interval": rule["pr_auc_interval"],
            }
        )
        rate = baselines["test"]["positive_rate"]
        rows.append(
            {
                "name": "constant",
                "label": "Constant score",
                "pr_auc": rate,
                "pr_auc_interval": [rate, rate],
            }
        )
    return rows


def alias_order(reports: dict[str, dict[str, Any]]) -> list[str]:
    """Best PR-AUC first, and the MLP always last, as it needs no tokenizer (PLAN.md, section 4).

    A model flagged by training_warnings ranks behind every healthy one, whatever its score.
    """
    ranked = sorted(
        (name for name in reports if name != MLP),
        key=lambda name: (not reports[name].get("training_warnings"), reports[name]["pr_auc"]),
        reverse=True,
    )
    return [*ranked, MLP] if MLP in reports else ranked


def clears_baselines(report: dict[str, Any], baselines: dict[str, Any]) -> bool:
    """The first champion has no champion to beat, so it must clearly beat the rule baseline: its
    interval has to sit entirely above the baseline's (PLAN.md, section 4)."""
    return bool(report["pr_auc_interval"][0] > baselines["test"]["rule"]["pr_auc_interval"][1])


def registered_versions() -> dict[str, str]:
    """Versions from the last registration, so a rerun without --register keeps them."""
    aliases = read_json(RUNS_FOLDER / "aliases.json") or {}
    return {entry["model"]: str(entry["version"]) for entry in aliases.values()}


def model_card(
    report: dict[str, Any],
    manifest: dict[str, Any],
    robustness: dict[str, Any] | None,
    benchmark: dict[str, Any] | None,
    golden: dict[str, Any] | None,
    version: str,
) -> str:
    cells = report["at_threshold"]
    low, high = report["pr_auc_interval"]
    recall_low, recall_high = report["recall_at_90_precision_interval"]
    lines = [
        f"# Model card: {charts.label_of(report['model'])} (version {version})",
        "",
        "Generated by `trainer.finish` from the run's own reports. Numbers are for the served",
        "int8 ONNX file, unless a line says otherwise.",
        "",
        "## What it does",
        "",
        "Ranks English Wikipedia article edits by how likely they are to be reverted within 48",
        "hours, so human patrollers read the riskiest first. It never reverts anything.",
        "",
        "**Not a vandalism detector in the strict sense:** a revert also covers good-faith",
        "mistakes, and some vandalism is never reverted. Don't use it to judge an editor.",
        "",
        "## Data",
        "",
        f"- Snapshot: `{manifest['name']}`",
        f"- Content hash when trained: `{report['snapshot_content_sha256']}`",
        f"- Windows: train up to {manifest['windows']['validation_start'][:10]}, validation to "
        f"{manifest['windows']['test_start'][:10]}, test to {manifest['windows']['end'][:10]}",
        f"- Training rows used: {report['train_rows']:,}",
        f"- Test rows: {report['rows']:,}, of which {report['positives']:,} reverted",
        "",
        "## Build",
        "",
        f"- MLflow run: `{report['run_id']}`",
        f"- Artifact checksum: `{report['artifact_sha256']}`",
        f"- Parameters: `{json.dumps(report['params'], sort_keys=True)}`",
        f"- Trained on: {report['device_name']}, in {report['fit']['seconds'] / 60:.1f} minutes",
        f"- Weights: {report['parameters']['total']:,} parameters, "
        f"{report['parameters']['trainable']:,} trained",
        f"- Served size: {report['served_bytes'] / 1e6:.1f} MB",
        "",
        "## Results on the test window",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| PR-AUC | {report['pr_auc']:.4f} (95% interval {low:.4f} to {high:.4f}) |",
        f"| ROC-AUC | {report['roc_auc']:.4f} |",
        f"| Recall at 90% precision | {report['recall_at_90_precision']:.4f} "
        f"(95% interval {recall_low:.4f} to {recall_high:.4f}) |",
        f"| Precision in the top 50 | {report['precision_at_50']:.2f} |",
        f"| Threshold rule | {report['threshold_rule']} |",
        f"| Precision at the threshold | {cells['precision']:.4f} |",
        f"| Recall at the threshold | {cells['recall']:.4f} |",
        f"| F1 at the threshold | {cells['f1']:.4f} |",
        f"| ECE before and after calibration | {report['ece_before']:.4f}, "
        f"{report['ece_after']:.4f} |",
        f"| PyTorch vs served PR-AUC gap | {report['parity']['test']['gap']:.5f} |",
        "",
        "## Slices",
        "",
        "| Slice | Rows | Reverted | PR-AUC | False positive rate |",
        "|---|---|---|---|---|",
    ]
    for name, values in report["slices"].items():
        if values["rows"]:
            lines.append(
                f"| {name} | {values['rows']:,} | {values['positives']:,} | "
                f"{values.get('pr_auc', float('nan')):.4f} | "
                f"{values['false_positive_rate']:.4%} |"
            )
        else:
            lines.append(f"| {name} | 0 | 0 | not measured | not measured |")
    gap = report["false_positive_gap_anonymous_minus_registered"]
    lines += ["", f"False positive gap, logged-out minus registered: {gap:.4%}.", ""]
    if benchmark:
        single = benchmark["single_edit"]
        lines += [
            "## Speed",
            "",
            f"One edit at a time, one thread, on {benchmark['label']} ({benchmark['machine']}): "
            f"p50 {single['p50_ms']:.1f} ms, p95 {single['p95_ms']:.1f} ms. Peak memory "
            f"{benchmark['peak_rss_mb']:.0f} MB. `arm64`: not measured.",
            "",
        ]
    if robustness:
        lines += [
            "## Robustness",
            "",
            f"Recall on {robustness['rows']:,} sampled edits was "
            f"{robustness['original_recall']:.3f} and PR-AUC {robustness['original_pr_auc']:.3f} "
            "before any change. The sample is half reverts, so read the drops, not the levels.",
            "",
            "| Disguise | Recall | Recall drop | PR-AUC | PR-AUC drop |",
            "|---|---|---|---|---|",
        ]
        for name, values in robustness["changes"].items():
            lines.append(
                f"| {name} | {values['recall']:.3f} | {values['recall_drop']:.3f} | "
                f"{values['pr_auc']:.3f} | {values['pr_auc_drop']:.3f} |"
            )
        lines.append("")
    if golden:
        lines += [
            "## Golden set",
            "",
            f"{golden['rows']} checked edits: PR-AUC {golden['pr_auc']:.4f}, recall at threshold "
            f"{golden['at_threshold']['recall']:.3f}, precision at threshold "
            f"{golden['at_threshold']['precision']:.3f}.",
            "",
        ]
    lines += [
        "## Limits",
        "",
        "- Labels are reverts, which are noisy. See `docs/error-analysis.md`.",
        "- Edit-count slices and the edit-count feature can't be used until live data exists,",
        "  because backfilled rows have no point-in-time count (DEC-036, F-070).",
        "- 63% of test rows are by editors also seen in train, so this isn't a score on unseen",
        "  editors (F-070).",
        "- Backfilled test data isn't live data. Live performance is measured from Phase 5.",
        "",
    ]
    return "\n".join(lines)


def _log_charts(client: MlflowClient, run_id: str, paths: list[Path]) -> None:
    for path in paths:
        client.log_artifact(run_id, str(path), "charts")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("snapshot", type=Path)
    parser.add_argument("--register", action="store_true")
    parser.add_argument("--skip-robustness", action="store_true")
    parser.add_argument("--day", type=date.fromisoformat, default=date.today())
    args = parser.parse_args()

    configure()
    client = MlflowClient()
    data = load_dataset(args.snapshot)
    reports = load_reports()
    day = args.day
    baselines = read_json(RUNS_FOLDER / "baselines.json")
    golden = read_json(GOLDEN_FILE)
    test_labels = labels_of(data.test)
    robustness_reports: dict[str, Any] = {}
    golden_reports: dict[str, Any] = {}
    curves: dict[str, tuple[Any, Any]] = {}

    for name, report in reports.items():
        folder = RUNS_FOLDER / name
        served = ServedModel(folder / "model", threads=SCORING_THREADS)
        stored = np.load(folder / SCORES_FILE, allow_pickle=False)
        curves[name] = (test_labels, stored["test_logit"])
        robustness_path = folder / "robustness.json"
        if not args.skip_robustness and not robustness_path.exists():
            result = robustness_report(served, data.test, report["threshold"])
            robustness_path.write_text(json.dumps(result, indent=2), "utf-8")
        if robustness_path.exists():
            robustness_reports[name] = read_json(robustness_path)
        if golden:
            golden_reports[name] = golden_report(served, golden, report["threshold"])
            (folder / "golden.json").write_text(json.dumps(golden_reports[name], indent=2), "utf-8")
        paths = [
            charts.confusion_matrix(report, IMAGES_FOLDER, day),
            charts.learning_curves(report, IMAGES_FOLDER, day),
            charts.reliability(report, IMAGES_FOLDER, day),
            charts.slices(report, IMAGES_FOLDER, day),
        ]
        _log_charts(client, report["run_id"], paths)

    shared = [
        charts.pr_curves(curves, float(test_labels.mean()), IMAGES_FOLDER, day),
        charts.leaderboard(leaderboard_rows(reports, baselines), IMAGES_FOLDER, day),
    ]
    if robustness_reports:
        shared.append(charts.robustness(robustness_reports, IMAGES_FOLDER, day))
    aging = read_json(RUNS_FOLDER / "aging.json")
    if aging:
        shared.append(charts.aging(aging, IMAGES_FOLDER, day))
    benchmarks = read_json(RUNS_FOLDER / "benchmarks" / "laptop.json")
    if benchmarks:
        ordered = [row for name in charts.MODEL_ORDER for row in benchmarks if row["model"] == name]
        shared.append(charts.latency(ordered, IMAGES_FOLDER, day))
    for report in reports.values():
        _log_charts(client, report["run_id"], shared)

    versions = registered_versions()
    if args.register:
        versions = {}
        for name in alias_order(reports):
            report = reports[name]
            metrics = {
                "pr_auc": report["pr_auc"],
                "recall_at_90_precision": report["recall_at_90_precision"],
            }
            version = register_version(
                report["run_id"], "model", name, report["artifact_sha256"], metrics
            )
            versions[name] = version.version
        order = alias_order(reports)
        if baselines and not clears_baselines(reports[order[0]], baselines):
            raise SystemExit(f"{order[0]} doesn't clearly beat the rule baseline")
        aliases = [("champion", versions[order[0]])]
        aliases += [
            (f"fallback-{index}", versions[name]) for index, name in enumerate(order[1:], 1)
        ]
        set_aliases(aliases)
        (RUNS_FOLDER / "aliases.json").write_text(
            json.dumps(
                {
                    alias: {
                        "version": version,
                        "model": next(name for name, value in versions.items() if value == version),
                    }
                    for alias, version in aliases
                },
                indent=2,
            ),
            "utf-8",
        )
        print(json.dumps(aliases))

    CARDS_FOLDER.mkdir(parents=True, exist_ok=True)
    for name, report in reports.items():
        benchmark = None
        if benchmarks:
            benchmark = next((row for row in benchmarks if row["model"] == name), None)
        version = versions.get(name, "not registered")
        text = model_card(
            report,
            data.manifest,
            robustness_reports.get(name),
            benchmark,
            golden_reports.get(name),
            version,
        )
        (CARDS_FOLDER / f"{name}.md").write_text(text, "utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
